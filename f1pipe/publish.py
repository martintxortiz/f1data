"""Upload outputs as GitHub release assets, one release per Grand Prix. Incremental: only new or changed files are uploaded."""
from __future__ import annotations

import glob
import json
import os
import shutil
import subprocess
import tempfile

from .pipeline import OUT_DIR

MAX_ASSET = 2 * 1024**3  # GitHub release asset limit


def _gh(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["gh", *args], capture_output=True, text=True, check=check)


def _assets(repo: str, tag: str) -> dict[str, int] | None:
    r = _gh("release", "view", tag, "--repo", repo, "--json", "assets", check=False)
    if r.returncode != 0:
        return None
    return {a["name"]: a["size"] for a in json.loads(r.stdout)["assets"]}


def publish(season: int, repo: str) -> None:
    for gp_dir in sorted(glob.glob(os.path.join(OUT_DIR, str(season), "*"))):
        manifests = sorted(glob.glob(os.path.join(gp_dir, "*.json")))
        manifests = [m for m in manifests if json.load(open(m))["verify"]["ok"]]
        if not manifests:
            continue
        info = json.load(open(manifests[0]))["info"]
        gp = os.path.basename(gp_dir)
        tag = f"data-{season}-r{info['round']:02d}-{gp.split('_', 1)[1]}"
        with tempfile.TemporaryDirectory() as tmp:
            files = []
            for m in manifests:
                name = os.path.basename(m)[:-5]
                files += [m, os.path.join(gp_dir, f"{name}.mcap")]
                files.append(shutil.make_archive(os.path.join(tmp, f"{name}_parquet"), "zip", os.path.join(gp_dir, name)))
            big = [f for f in files if os.path.getsize(f) >= MAX_ASSET]
            if big:  # never happened so far (largest race MCAP is far below 2 GB); refuse rather than upload a broken asset
                raise SystemExit(f"{tag}: assets over 2 GB need splitting by topic: {big}")
            existing = _assets(repo, tag)
            if existing is None:
                notes = (f"{info['official_event_name']} — OpenF1 data as MCAP (Foxglove) + Parquet, one file per session. "
                         "Format: docs/MCAP_FORMAT.md. Generated by `python -m f1pipe`.")
                _gh("release", "create", tag, "--repo", repo, "--title", f"Data {season} R{info['round']:02d} {info['event_name']}",
                    "--notes", notes, "--latest=false")
                existing = {}
            todo = [f for f in files if existing.get(os.path.basename(f)) != os.path.getsize(f)]
            # zips are rebuilt every run; re-upload them only when their session's MCAP changed or they are missing
            todo = [f for f in todo if not f.endswith("_parquet.zip") or os.path.basename(f) not in existing
                    or any(t.endswith(os.path.basename(f).replace("_parquet.zip", ".mcap")) for t in todo)]
            if todo:
                _gh("release", "upload", tag, *todo, "--repo", repo, "--clobber")
            print(f"{tag}: {len(todo)} uploaded, {len(files) - len(todo)} unchanged -> https://github.com/{repo}/releases/tag/{tag}", flush=True)
